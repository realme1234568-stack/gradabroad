import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const programs = JSON.parse(await readFile(new URL("data/programs-germany-english.json", root), "utf8"));
if (programs.length !== 200 || ["bachelor", "master"].some(level => programs.filter(p => p.level === level).length !== 100)) throw new Error("Expected 100 bachelor and 100 master programs");
if (new Set(programs.map(p => p.id)).size !== 200 || new Set(programs.map(p => `${p.university_name}|${p.course_name}`)).size !== 200) throw new Error("Duplicate catalogue entries");
for (const p of programs) {
  if (!p.details?.english_taught || p.details.institution_type !== "public" || p.language !== "English") throw new Error("Out-of-scope catalogue entry");
}
const payload = JSON.stringify(programs);
if (payload.includes("$catalogue$")) throw new Error("Unexpected SQL delimiter");
const sql = `-- Initial editorial snapshot: 100 public English-taught programs per degree.
-- Generated by scripts/build-program-seed.mjs from data/programs-germany-english.json.
-- Re-running never overwrites later owner edits, publication choices, or student data.
-- Apply 20261020190000_program_details.sql first.
begin;
create temporary table catalogue_seed (id uuid,university_name text,course_name text,level text,language text,is_published boolean,details jsonb) on commit drop;
insert into catalogue_seed select * from jsonb_to_recordset($catalogue$${payload}$catalogue$::jsonb)
  as p(id uuid,university_name text,course_name text,level text,language text,is_published boolean,details jsonb);
do $$ begin
  if (select count(*) from catalogue_seed)<>200
    or (select count(*) from catalogue_seed where level='bachelor')<>100
    or (select count(*) from catalogue_seed where level='master')<>100
    or exists(select 1 from catalogue_seed where not public.program_details_valid(details) or not (details->>'english_taught')::boolean or language<>'English') then
    raise exception 'Invalid editorial catalogue snapshot';
  end if;
  -- A legacy row with the same name needs deliberate reconciliation, never a silent skip.
  if exists(select 1 from catalogue_seed s join public.programs p
      on p.university_name=s.university_name and p.course_name=s.course_name where p.id<>s.id) then
    raise exception 'Existing university/course name conflicts with the import. Reconcile before importing.';
  end if;
end $$;
insert into public.programs(id,university_name,course_name,level,language,is_published,details)
  select id,university_name,course_name,level,language,is_published,details from catalogue_seed
  on conflict(id) do nothing;
-- Existing shortlists and unreviewed legacy programs are intentionally retained.
-- Discovery only returns records carrying the reviewed public/English metadata.
commit;
`;
const target = new URL("supabase/migrations/20261021010000_german_english_catalogue.sql", root);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== sql) throw new Error("Seed SQL does not match the editorial JSON; regenerate before release");
  console.log("Catalogue JSON and SQL agree: 200 entries.");
} else {
  await writeFile(target, sql);
  console.log(`Generated ${fileURLToPath(target)}`);
}
